/**
 * Shared HTML wrappers for print-friendly documents.
 * Zero deps — the browser's own "Save as PDF" handles conversion.
 * ?auto=1 triggers window.print() on load.
 */
export function documentShell(opts: {
  title: string;
  companyName?: string;
  gstin?: string;
  address?: string;
  bodyHtml: string;
  auto?: boolean;
}): Response {
  const printTrigger = opts.auto
    ? `<script>window.addEventListener('load',()=>{setTimeout(()=>window.print(),100)})</script>`
    : '';
  const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>${escapeHtml(opts.title)}</title>
<style>
  *,*::before,*::after{box-sizing:border-box}
  html,body{margin:0;padding:0;font-family:-apple-system,BlinkMacSystemFont,"Segoe UI",Roboto,sans-serif;font-size:13px;color:#111}
  .page{max-width:210mm;margin:12mm auto;padding:16mm;background:#fff}
  header{display:flex;justify-content:space-between;align-items:flex-start;border-bottom:2px solid #111;padding-bottom:8px;margin-bottom:16px}
  header .right{text-align:right;font-size:11px;color:#555;line-height:1.5}
  h1{font-size:18px;margin:0 0 4px}
  h2{font-size:14px;margin:16px 0 6px}
  table{width:100%;border-collapse:collapse;margin:6px 0}
  th,td{border:1px solid #ccc;padding:6px 8px;text-align:left;vertical-align:top}
  th{background:#f4f4f4;font-weight:600}
  .right{text-align:right}
  .muted{color:#666}
  .total{font-size:15px;font-weight:700;border-top:2px solid #111;padding-top:8px;margin-top:8px;text-align:right}
  footer{margin-top:24px;padding-top:12px;border-top:1px solid #ccc;font-size:10px;color:#666;display:flex;justify-content:space-between}
  .signatory{margin-top:32px;text-align:right}
  .signatory .line{border-top:1px solid #111;width:200px;display:inline-block;padding-top:4px}
  @media print {
    .page{margin:0;padding:12mm;max-width:none}
    .no-print{display:none!important}
    @page{size:A4;margin:0}
  }
  .no-print{position:fixed;top:8px;right:8px;background:#111;color:#fff;border:0;padding:8px 12px;border-radius:6px;cursor:pointer;font-size:12px}
</style>
</head>
<body>
<button class="no-print" onclick="window.print()">Print / Save as PDF</button>
<div class="page">
  <header>
    <div>
      <h1>${escapeHtml(opts.companyName ?? 'RealtyCRM')}</h1>
      ${opts.address ? `<div class="muted" style="white-space:pre-line">${escapeHtml(opts.address)}</div>` : ''}
    </div>
    <div class="right">
      ${opts.gstin ? `<div>GSTIN: ${escapeHtml(opts.gstin)}</div>` : ''}
      <div>${new Date().toLocaleDateString('en-IN', { day: '2-digit', month: 'short', year: 'numeric' })}</div>
    </div>
  </header>
  ${opts.bodyHtml}
  <footer>
    <span>Generated by RealtyCRM · ${new Date().toISOString()}</span>
    <span>Page 1 of 1</span>
  </footer>
</div>
${printTrigger}
</body>
</html>`;
  return new Response(html, { headers: { 'Content-Type': 'text/html; charset=utf-8' } });
}

export function escapeHtml(s: string | null | undefined): string {
  if (s == null) return '';
  return String(s)
    .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;').replace(/'/g, '&#39;');
}

export function inr(n: number | string | null | undefined): string {
  const v = Number(n ?? 0);
  return '₹' + v.toLocaleString('en-IN', { maximumFractionDigits: 2 });
}
